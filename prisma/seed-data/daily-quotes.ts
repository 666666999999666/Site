const EXPECTED_PER_GROUP = 61
if (groups.some((group) => group.quotes.length !== EXPECTED_PER_GROUP)) {
  throw new Error("Each daily quote category must contain exactly 61 quotes")
}

const interleaved = Array.from({ length: EXPECTED_PER_GROUP }, (_, quoteIndex) =>
  groups.map((group) => ({
    category: group.category,
    quote: group.quotes[quoteIndex],
  }))
).flat()

const dates = Array.from({ length: 366 }, (_, index) => {
  const date = new Date(Date.UTC(2000, 0, 1 + index))
  return date.toISOString().slice(0, 10)
})

export const DAILY_QUOTE_SEED = interleaved.map((item, index) => ({
  ...item,
  author: "QZ Site",
  source: "每日提醒语",
  sourceDetail: `${item.category}主题`,
  usedDate: dates[index],
  normalizedHash: createHash("sha256")
    .update(item.quote.normalize("NFKC").replace(/\s+/g, " ").trim(), "utf8")
    .digest("hex"),
}))

if (DAILY_QUOTE_SEED.length !== 366) throw new Error("Daily quote seed must contain 366 rows")
if (new Set(DAILY_QUOTE_SEED.map((item) => item.quote)).size !== 366) {
  throw new Error("Daily quote seed contains duplicate text")
}
